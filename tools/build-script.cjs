#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sourceRoot = path.join(root, 'src', 'app');
const outputPath = path.join(root, 'script.js');
const sections = [
    '00-hardware-library.js',
    '01-state-and-preferences.js',
    '02-room-and-canvas-theme.js',
    '03-canvas-navigation.js',
    '04-device-catalog-model.js',
    '05-audio-model-and-routing.js',
    '06-audio-runtime-and-meters.js',
    '07-audio-sources.js',
    '08-catalog-ui.js',
    '09-recording-and-test-equipment.js',
    '10-integrated-equipment.js',
    '11-device-creation.js',
    '12-device-interactions.js',
    '13-inspector-and-history.js',
    '14-cable-rendering-and-drag.js',
    '15-signal-validation-and-connections.js',
    '16-cable-routing-and-live-visuals.js',
    '17-spotify-objects.js',
    '18-project-storage.js',
    '19-settings-ui.js',
    '20-guided-access-and-startup.js',
];

const banner = '/* Generated by tools/build-script.cjs from src/app. Edit the source sections instead. */\n';
function buildOutput() {
    return banner + sections.map(file => {
    const sourcePath = path.join(sourceRoot, file);
    if (!fs.existsSync(sourcePath)) throw new Error(`Missing application source section: ${sourcePath}`);
    const section = fs.readFileSync(sourcePath, 'utf8');
    const headerEnd = section.indexOf('\n');
    if (headerEnd < 0 || !section.startsWith('/* ')) throw new Error(`Missing section description: ${sourcePath}`);
    return section.slice(headerEnd + 1);
    }).join('');
}

function checkOutput(output = buildOutput()) {
    const current = fs.readFileSync(outputPath, 'utf8');
    if (current !== output) {
        throw new Error('script.js is out of date. Run: node tools/build-script.cjs');
    }
}

if (require.main === module) {
    const output = buildOutput();
    if (process.argv.includes('--check')) {
        try {
            checkOutput(output);
            console.log(`script.js is current (${sections.length} source sections).`);
        } catch (error) {
            console.error(error.message);
            process.exitCode = 1;
        }
    } else {
        fs.writeFileSync(outputPath, output);
        console.log(`Built script.js from ${sections.length} source sections.`);
    }
}

module.exports = {sections, buildOutput, checkOutput};
