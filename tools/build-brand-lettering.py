#!/usr/bin/env python3
"""Shape deterministic SVG lettering from vendored OFL fonts.
Requires: fonttools, uharfbuzz. No font resources are requested at runtime.
"""
import json
from pathlib import Path
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen
ROOT=Path(__file__).resolve().parents[1]
SOURCES={
'aurenne':('Pacifico-Regular.ttf','Aurenne','Au'),
'veltron':('Audiowide-Regular.ttf','VELTRON','VT'),
'nexora':('Righteous-Regular.ttf','nexora','nx'),
'korden':('Bungee-Regular.ttf','KORDEN','KR'),
'linholt':('Audiowide-Regular.ttf','linholt','lh'),
'bravora':('DMSerifDisplay-Regular.ttf','Bravora','Br'),
'soryn':('Righteous-Regular.ttf','soryn','sy'),
'terevon':('DMSerifDisplay-Regular.ttf','Terevon','Te'),
'axiomer':('Bungee-Regular.ttf','AXIOMER','AX'),
'dovara':('ChangaOne-Regular.ttf','DOVARA','DV'),
}
def outline(file,word,box,slant=0):
    tt=TTFont(file);glyphs=tt.getGlyphSet();order=tt.getGlyphOrder()
    face=hb.Face(file.read_bytes());font=hb.Font(face);buf=hb.Buffer();buf.add_str(word);buf.guess_segment_properties();hb.shape(font,buf)
    shaped=[];cursor=0
    for info,pos in zip(buf.glyph_infos,buf.glyph_positions):
        shaped.append((order[info.codepoint],cursor+pos.x_offset,pos.y_offset));cursor+=pos.x_advance
    bounds=BoundsPen(glyphs)
    for name,x,y in shaped:glyphs[name].draw(TransformPen(bounds,(1,0,slant,1,x,y)))
    x0,y0,x1,y1=bounds.bounds;left,top,width,height=box;scale=min(width/(x1-x0),height/(y1-y0))
    dx=left+(width-(x1-x0)*scale)/2-x0*scale;dy=top+(height-(y1-y0)*scale)/2+y1*scale
    pen=SVGPathPen(glyphs,ntos=lambda n:format(n,'.2f').rstrip('0').rstrip('.') if isinstance(n,float) else str(n))
    for name,x,y in shaped:glyphs[name].draw(TransformPen(pen,(scale,0,slant*scale,-scale,dx+x*scale,dy-y*scale)))
    return pen.getCommands(),[round(dx+x0*scale-1,2),round(dy-y1*scale-1,2),round((x1-x0)*scale+2,2),round((y1-y0)*scale+2,2)]
result={}
for brand,(filename,word,compact) in SOURCES.items():
    file=ROOT/'assets/fonts/brand-identities'/filename
    slant=.16 if brand in ['korden','axiomer'] else 0
    path,bounds=outline(file,word,(54,5,172,30),slant);small,_=outline(file,compact,(3,3,42,31),slant)
    result[brand]={'word':word,'path':path,'bounds':bounds,'compact':compact,'compactPath':small,'source':filename}
output='/* Generated by tools/build-brand-lettering.py from OFL fonts. */\n((root,data)=>{if(typeof module===\'object\'&&module.exports)module.exports=data;else root.BrandLettering=data;})(globalThis,'+json.dumps(result,separators=(',',':'))+');\n'
(ROOT/'src/modules/brand-lettering.js').write_text(output)
print('Outlined ten wordmarks and their compact typographic signatures.')
